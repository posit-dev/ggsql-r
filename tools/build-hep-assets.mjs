// Generates inst/htmlwidgets/lib/hephaestus-svg/hephaestus-assets.js from the
// installed hephaestus-svg-wasm npm package. The wasm binary and Roboto font
// faces are gzip-compressed, base64-encoded, and assigned to a single global
// (`globalThis.ggsqlHepAssets`) so the widget never has to resolve asset URLs
// — the file travels with the htmlDependency, which htmltools includes exactly
// once per document, inlined or served.
//
// Run via: node tools/build-hep-assets.mjs  (also called by
// tools/update-hephaestus.sh after a version bump)

import { gzipSync } from "node:zlib";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const moduleDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(moduleDir, "..");
const pkgDir = path.join(repoRoot, "node_modules", "hephaestus-svg-wasm");
const outDir = path.join(repoRoot, "inst", "htmlwidgets", "lib", "hephaestus-svg");

const version = JSON.parse(
  readFileSync(path.join(pkgDir, "package.json"), "utf8"),
).version;

const ROBOTO_FACES = ["regular", "bold", "italic", "bolditalic"];

function encode(file) {
  return gzipSync(readFileSync(file), { level: 9 }).toString("base64");
}

const payload = {
  version,
  wasm: encode(path.join(pkgDir, "hephaestus_svg_wasm_bg.wasm")),
  fonts: Object.fromEntries(
    ROBOTO_FACES.map((face) => [
      face,
      encode(path.join(pkgDir, "fonts", `roboto-${face}.ttf`)),
    ]),
  ),
};

mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, "hephaestus-assets.js");
writeFileSync(
  outFile,
  `// AUTO-GENERATED by tools/build-hep-assets.mjs — do not edit by hand.
// hephaestus-svg-wasm@${version} wasm + Roboto faces, gzip-compressed and
// base64-encoded. Decoded by srcts/hep/widget.ts at module load.
globalThis.ggsqlHepAssets = ${JSON.stringify(payload)};
`,
);

const rawKb =
  JSON.stringify(payload).length / 1024;
console.log(
  `Wrote ${outFile} (${rawKb.toFixed(0)} KB) for hephaestus-svg-wasm@${version}`,
);
